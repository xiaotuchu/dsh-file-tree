/**
 * Build both halves.
 *
 *   node scripts/build.mjs      writes lib/index.js + lib/client.js
 *
 * `lib/index.js` is a plain ESM module the loader imports on the host side.
 * `lib/client.js` is the browser bundle shaped the way `dsh-client-modules`
 * expects it: one `window.__ModuleLoader__.load({ id, factory })` call whose
 * factory receives the host's `require` and returns the module exports. Every
 * `react*` and `@deepseek-ai/*` import stays external and resolves through that
 * table, so the bundle never ships a second copy of React.
 */
import { build } from 'esbuild'
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const root = resolve(here, '..')
const outDir = resolve(root, 'lib')

const manifest = JSON.parse(await readFile(resolve(root, 'package.json'), 'utf8'))
const pkgName = manifest.name

/** Host-provided modules. Wildcards are supported by esbuild. */
const external = ['react', 'react-dom', 'react/jsx-runtime', 'react-dom/client', '@deepseek-ai/*']

function indent(text) {
  return text
    .split('\n')
    .map((line) => (line === '' ? '' : `\t\t${line}`))
    .join('\n')
}

async function buildNode() {
  await build({
    entryPoints: [resolve(root, 'src/node/index.ts')],
    outfile: resolve(outDir, 'index.js'),
    bundle: true,
    format: 'esm',
    platform: 'node',
    target: 'node20',
    external,
    logLevel: 'warning',
    banner: { js: '// Generated by scripts/build.mjs from src/node — do not edit.' }
  })
}

async function buildClient() {
  const result = await build({
    entryPoints: [resolve(root, 'src/client/index.ts')],
    bundle: true,
    write: false,
    format: 'cjs',
    platform: 'browser',
    target: 'es2020',
    jsx: 'automatic',
    external,
    logLevel: 'warning',
    legalComments: 'none'
  })
  // With `write: false` and no outfile, esbuild names the single output
  // "<stdout>" — so take the first file rather than matching on a .js suffix.
  const file = result.outputFiles[0]
  if (file === undefined) throw new Error('esbuild produced no output for the client half')
  const wrapped =
    `/* ${pkgName} — generated by scripts/build.mjs from src/client — do not edit. */\n` +
    'window.__ModuleLoader__.load({\n' +
    `\tid: ${JSON.stringify(pkgName)},\n` +
    '\tfactory: (require) => {\n' +
    '\t\tvar module = { exports: {} };\n' +
    '\t\tvar exports = module.exports;\n' +
    indent(file.text.trimEnd()) +
    '\n\t\treturn module.exports;\n' +
    '\t}\n' +
    '});\n'
  await writeFile(resolve(outDir, 'client.js'), wrapped, 'utf8')
  return wrapped.length
}

await mkdir(outDir, { recursive: true })
await buildNode()
const clientBytes = await buildClient()
for (const name of ['index.js', 'client.js']) {
  const bytes = (await readFile(resolve(outDir, name))).byteLength
  console.log(`  lib/${name.padEnd(10)} ${(bytes / 1024).toFixed(1)} KB`)
}
console.log(`built ${pkgName} — client bundle ${(clientBytes / 1024).toFixed(1)} KB`)
